private val LocalUrgencyPalette = staticCompositionLocalOf { LightUrgency }

/** Theme values that Material has no slot for. */
object GoodBefore {
    val urgency: UrgencyPalette
        @Composable @ReadOnlyComposable get() = LocalUrgencyPalette.current
}

/**
 * Light and dark, following the system by default.
 *
 * Dynamic colour is deliberately off. The wallpaper-derived palette is a fine
 * default for an app with no view of its own, but the point of authoring this
 * one is that expiry states and the accent carry meaning; handing them to the
 * wallpaper would make "urgent" a different colour on every device.
 *
 * Nothing here sets `window.statusBarColor`. It is deprecated and ignored from
 * API 35, where edge-to-edge is enforced, and this app targets 36 — the old
 * call was painting a bar the system had already stopped drawing.
 */
@Composable
fun FreshTrackTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColors else LightColors
    val urgency = if (darkTheme) DarkUrgency else LightUrgency

    CompositionLocalProvider(LocalUrgencyPalette provides urgency) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            content = content
        )
    }
}
